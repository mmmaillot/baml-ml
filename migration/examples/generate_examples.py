"""Generate runnable BAML examples from the original deterministic splits.

Python only loads datasets and computes the independent sklearn oracle.
Training, preprocessing, inference and comparison run in BAML.
"""
from pathlib import Path
import math
import sys

import numpy as np
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LinearRegression, LogisticRegression
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from benchmarks.datasets import MISSING_FRAC, load_split

OUT = ROOT / "migration" / "baml_src" / "generated_examples.baml"


def literal(value):
    if isinstance(value, np.ndarray):
        return literal(value.tolist())
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(literal(v) for v in value) + "]"
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    value = float(value)
    if math.isnan(value):
        return "float.nan()"
    if not math.isfinite(value):
        raise ValueError("unexpected infinity in fixture")
    return repr(value)


def generate(name, missing_frac):
    split = load_split(name, missing_frac=missing_frac)
    classification = name == "iris"
    estimator = (
        LogisticRegression(C=1.0, tol=1e-10, max_iter=10000)
        if classification else LinearRegression()
    )
    ref = Pipeline([
        ("imputer", SimpleImputer(strategy="mean")),
        ("scaler", StandardScaler()),
        ("model", estimator),
    ]).fit(split.x_train, split.y_train)
    # Independent train-only preprocessing references, as in test_examples.py.
    means = np.nanmean(split.x_train, axis=0)
    imputed = np.where(np.isnan(split.x_train), means, split.x_train)
    scaler_means = imputed.mean(axis=0)
    assert split.x_train.shape[0] == (120 if classification else 353)
    assert split.x_test.shape[0] == (30 if classification else 89)
    suffix = "Missing" if missing_frac else "Clean"
    fn = name.capitalize() + suffix
    y = split.y_train.astype(int if classification else float)
    expected = ref.predict_proba(split.x_test) if classification else ref.predict(split.x_test)
    args = [split.x_train, y, split.x_test, expected]
    if classification:
        args.append(ref.predict(split.x_test).astype(int))
    args.extend([means, scaler_means])
    checker = "CheckIrisExample" if classification else "CheckDiabetesExample"
    # Separate array helper functions keep generated bytecode functions small.
    types = ["float[][]", "int[]" if classification else "float[]",
             "float[][]", "float[][]" if classification else "float[]"]
    if classification:
        types.append("int[]")
    types.extend(["float[]", "float[]"])
    helpers = []
    calls = []
    for i, (arg, ty) in enumerate(zip(args, types, strict=True)):
        helper = f"Fixture{fn}{i}"
        helpers.append(f"function {helper}() -> {ty} {{ {literal(arg)} }}")
        calls.append(helper + "()")
    tol = "1e-3" if classification else "1e-9"
    code = "\n".join(helpers)
    code += f"""
function Example{fn}() -> ExampleResult {{
    {checker}({', '.join(calls)})
}}
test "example_{name}_{suffix.lower()}" {{
    let r = Example{fn}();
    assert.equal(r.error, "")
    assert.is_true(r.ok)
    assert.is_true(r.max_prediction_diff <= {tol})
    assert.is_true(r.max_imputer_mean_diff <= 1e-12)
    assert.is_true(r.max_scaler_mean_diff <= 1e-12)
    assert.is_true(r.labels_match)
}}
"""
    return code


def main():
    blocks = [
        generate(name, missing)
        for name in ("iris", "diabetes")
        for missing in (0.0, MISSING_FRAC)
    ]
    OUT.write_text("// Generated; do not edit or commit.\n\n" + "\n".join(blocks))
    print(f"Generated four BAML examples: {OUT}")


if __name__ == "__main__":
    main()
